CREATE VIEW LOANS_VIEW AS
    SELECT
        LOAN_ID, CUSTOMER_ID,
        (SELECT NAME FROM CUSTOMERS WHERE CUSTOMER_ID = L.CUSTOMER_ID) AS CUSTOMER_NAME,
        BRANCH_ID,
        (SELECT NAME FROM BRANCHES WHERE BRANCH_ID = L.BRANCH_ID) AS BRANCH_NAME,
        AMOUNT, LOAN_DATE, STATUS
    FROM LOANS L
;


CREATE VIEW EMPLOYEES_VIEW AS
    SELECT
        EMPLOYEE_ID, NAME, MANAGER_ID,
        (SELECT NAME FROM EMPLOYEES WHERE E.MANAGER_ID = EMPLOYEE_ID) AS MANAGER_NAME,
        SALARY, JOB_ID, DEPARTMENT_ID,
        (SELECT DEPARTMENT_NAME FROM DEPARTMENTS WHERE DEPARTMENT_ID = E.DEPARTMENT_ID) AS DEPARTMENT_NAME,
        HIRE_DATE
    FROM EMPLOYEES E;

CREATE VIEW HIERARCHICAL_EMPLOYEES_VIEW AS
    SELECT
        LEVEL LV, EMPLOYEE_ID, NAME, MANAGER_ID, MANAGER_NAME,
        SALARY, JOB_ID, DEPARTMENT_NAME, HIRE_DATE,
        SYS_CONNECT_BY_PATH(NAME, '->') AS NAME_PATH,
        SYS_CONNECT_BY_PATH(DEPARTMENT_NAME, '->') AS DEPARTMENT_PATH
    FROM EMPLOYEES_VIEW
    START WITH MANAGER_ID IS NULL
    CONNECT BY PRIOR EMPLOYEE_ID = MANAGER_ID
;


CREATE VIEW HIERARCHICAL_SHOPPING_CATEGORIES_VIEW AS
    SELECT LEVEL AS LEVEL, CATEGORY_ID, PARENT_CATEGORY_ID, CATEGORY_NAME
    FROM SHOPPING_CATEGORIES
    START WITH PARENT_CATEGORY_ID IS NULL
    CONNECT BY PRIOR CATEGORY_ID = PARENT_CATEGORY_ID
;


CREATE VIEW TRANSACTIONS_VIEW AS
    SELECT
        TRANSACTION_ID, T.ACCOUNT_ID,
        C.CUSTOMER_ID CUSTOMER_ID,
        C.NAME CUSTOMER_NAME, EMAIL, PHONE, ADDRESS,
        A.CREATED_AT ACCOUNT_CREATED_AT,
        C.CREATED_AT CUSTOMER_CREATED_AT,
        BALANCE, AMOUNT, TRANSACTION_TYPE, TRANSACTION_DATE
    FROM TRANSACTIONS T
    LEFT JOIN ACCOUNTS A
        ON T.ACCOUNT_ID = A.ACCOUNT_ID
    LEFT OUTER JOIN CUSTOMERS C
        ON C.CUSTOMER_ID = A.CUSTOMER_ID
;






