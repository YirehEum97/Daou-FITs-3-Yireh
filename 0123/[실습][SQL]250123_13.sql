    SUM_AMOUNT, AVG_AMOUNT
FROM
    (SELECT
        DISTINCT BRANCH_ID,
        SUM(AMOUNT) OVER(PARTITION BY BRANCH_ID) SUM_AMOUNT,
        ROUND(AVG(AMOUNT) OVER(),2) AVG_AMOUNT
    FROM LOANS_VIEW) T
