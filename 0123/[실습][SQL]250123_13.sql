SELECT
    DEPARTMENT_ID, NAME, SALARY,
    SUM(SALARY) OVER(PARTITION BY DEPARTMENT_ID
        ORDER BY SALARY RANGE BETWEEN 100 PRECEDING
        AND 100 FOLLOWING) AS TSAL
FROM EMPLOYEES;

