SELECT E.NAME, D.LOCATION
FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
;

-- 2
SELECT E1.NAME, E2.NAME
FROM EMPLOYEES E1
LEFT JOIN EMPLOYEES E2
    ON E1.EMPLOYEE_ID = E2.MANAGER_ID
;


-- 3번 급여가 NULL인 경우 N/A 반환
SELECT NAME, NVL(to_char(SALARY), 'N/A') AS SALARY
FROM EMPLOYEES;

-- 4
SELECT NAME, SALARY
FROM EMPLOYEES
WHERE DEPARTMENT_ID IN (
    SELECT DEPARTMENT_ID
    FROM DEPARTMENTS
    WHERE LOCATION = 'Chicago'
    )
;

-- 5
SELECT E.NAME, E.SALARY, D.DEPARTMENT_NAME AS DEPARTMENT
FROM (SELECT * FROM EMPLOYEES WHERE SALARY BETWEEN 5e3 AND 1e4) E
INNER JOIN DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
;

-- 6번 최근 3개월 내 입사한 직원
SELECT NAME, HIRE_DATE
FROM EMPLOYEES
WHERE MONTHS_BETWEEN(SYSDATE, HIRE_DATE) <= 3
;


